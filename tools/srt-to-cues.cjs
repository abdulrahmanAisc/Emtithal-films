// Generates src/subtitles.js from the SRT (brief 14.1 rule 10) plus the 8.1 keyword-lift table.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const srt = fs.readFileSync(path.join(root, 'emtithal-ask-the-code-subtitles-ar.srt'), 'utf8').replace(/\r/g, '');

const LIFT = {
  1: ['وآلاف'], 2: ['واحد'], 3: ['البند؟'], 4: ['مشروعي؟'], 5: ['امتثال،'], 6: ['بالمعنى.'],
  7: ['الدرج؟'], 8: ['البند،'], 9: ['الأصلية.'], 10: ['كلمة', 'بكلمة.'], 11: ['ببساطة.'],
  12: ['استثناءاته،'], 13: ['مشروعي؟'], 14: ['جواب؟'], 15: ['أعرف.'], 16: ['{N}', 'بمرجع.'],
  17: [], 18: ['الكود…'],
};
const toSec = (s) => { const m = s.match(/(\d+):(\d+):(\d+),(\d+)/); return +m[1] * 3600 + +m[2] * 60 + +m[3] + +m[4] / 1000; };
const cues = srt.trim().split(/\n\n+/).map((b) => {
  const l = b.split('\n');
  const n = +l[0];
  const [a, z] = l[1].split(' --> ').map(toSec);
  return { n, in: a, out: z, lines: l.slice(2), lift: LIFT[n] || [] };
});
for (const c of cues) for (const w of c.lift) {
  if (!c.lines.join(' ').split(' ').includes(w)) throw new Error(`cue ${c.n}: lift word "${w}" is not a whole word of the cue`);
}
fs.writeFileSync(path.join(root, 'src/subtitles.js'),
  '// GENERATED by tools/srt-to-cues.cjs from emtithal-ask-the-code-subtitles-ar.srt. Do not edit.\nFILM.SUBS = ' + JSON.stringify(cues, null, 1) + ';\n');
console.log('cues', cues.length);
